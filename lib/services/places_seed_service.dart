/// تقرير نتيجة الـ Seed.
class SeedReport {
  const SeedReport({
    required this.success,
    required this.written,
    required this.errorCount,
    required this.errors,
  });

  const SeedReport.failure(String msg)
      : success = false,
        written = 0,
        errorCount = 1,
        errors = const [];

  final bool success;
  final int written;
  final int errorCount;
  final List<String> errors;

  @override
  String toString() => success
      ? 'SeedReport(✅ $written written)'
      : 'SeedReport(❌ $errorCount errors)';
}
