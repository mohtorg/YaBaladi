  /// يُشغِّل الـ seed كاملاً. يعيد تقريراً بالنتائج.
  static Future<SeedReport> seedAll() async {
    final user = FirebaseAuth.instance.currentUser;
    if (user == null) {
      return const SeedReport.failure('سجّل دخولك أولاً (Admin/Merchant)');
    }

    final ownerId = user.uid;
    final fs = FirebaseFirestore.instance;
    final allErrors = <String>[];
    int written = 0;

    debugPrint('════════ 🌱 SEED START ════════');
    debugPrint('🌱 Owner: $ownerId');
    debugPrint('🌱 Total places: ${_places.length}');

    for (var i = 0; i < _places.length; i += _batchSize) {
      final batch = fs.batch();
      final slice = _places.sublist(
        i,
        (i + _batchSize).clamp(0, _places.length),
      );

      for (final place in slice) {
        final id = place['id'] as String;
        final data = Map<String, dynamic>.from(place)
          ..remove('id')
          ..['ownerId'] = ownerId
          ..['updatedAt'] = FieldValue.serverTimestamp();
        data.putIfAbsent('createdAt', () => FieldValue.serverTimestamp());

        batch.set(
          fs.collection(_collection).doc(id),
          data,
          SetOptions(merge: true),
        );
        written++;
      }

      try {
        await batch.commit();
        debugPrint('🌱 Batch ${i ~/ _batchSize + 1} committed '
            '(${slice.length} places)');
      } on FirebaseException catch (e) {
        allErrors.add('Batch ${i ~/ _batchSize + 1}: ${e.message}');
        debugPrint('🌱 ❌ Batch failed: ${e.message}');
      }
    }

    debugPrint('🌱 Written: $written, Errors: ${allErrors.length}');
    debugPrint('════════ 🌱 SEED END ════════');

    return SeedReport(
      success: allErrors.isEmpty,
      written: written,
      errorCount: allErrors.length,
      errors: allErrors,
    );
  }

